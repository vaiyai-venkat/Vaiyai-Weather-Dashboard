import assert from 'node:assert/strict';
import {pressureMidpoint,enrichInterval,VARIABLES,comparisonSlots,periodWindow,previousAnchor,alignPeriod,axisDomain,seriesSummary} from '../dist/comparison.mjs';
assert.equal(pressureMidpoint({pressure_min:1000,pressure_max:1012}),1006);
assert.equal(pressureMidpoint({pressure_min:null,pressure_max:1012}),null);
const old=enrichInterval({pressure:1013});assert.equal(old.pressure_max,1013);assert.equal(old.pressure_mid,null);
assert.deepEqual(periodWindow('week','2026-01-03'),{start:'2025-12-28',end:'2026-01-03'});
assert.deepEqual(periodWindow('month','2024-02-15'),{start:'2024-02-01',end:'2024-02-29'});
assert.deepEqual(periodWindow('month','2023-02-15'),{start:'2023-02-01',end:'2023-02-28'});
assert.deepEqual(periodWindow('year','2026-10-24'),{start:'2026-01-01',end:'2026-12-31'});
assert.equal(previousAnchor('month','2026-03-31'),'2026-02-28');
assert.equal(previousAnchor('year','2024-02-29'),'2023-02-28');
assert.equal(comparisonSlots('year').length,366);
const slots=comparisonSlots('year'),nonLeap=alignPeriod([{date:'2023-03-01',temp_avg:25}],'year','2023-01-01',slots);
assert.equal(nonLeap[slots.findIndex(s=>s.key==='02-29')].valid,false);
assert.equal(nonLeap[slots.findIndex(s=>s.key==='03-01')].row.temp_avg,25);
const leap=alignPeriod([{date:'2024-02-29',temp_avg:29}],'year','2024-01-01',slots);
assert.equal(leap[slots.findIndex(s=>s.key==='02-29')].row.temp_avg,29);
const feb=alignPeriod([],'month','2023-02-01');assert.equal(feb[28].date,null);
const rain=VARIABLES.find(v=>v.key==='rain_total'),dir=VARIABLES.find(v=>v.key==='wind_dir');
const rainy=alignPeriod([{date:'2026-10-18',rain_total:2},{date:'2026-10-24',rain_total:3}],'week','2026-10-24');
assert.deepEqual(seriesSummary(rainy,rain),{count:2,value:5,kind:'Total'});
assert.equal(rainy[1].row,null);assert.equal(seriesSummary(alignPeriod([],'week','2026-10-24'),rain).value,null);
assert.ok(Math.abs(seriesSummary([{row:{wind_dir:350}},{row:{wind_dir:10}}],dir).value)<1e-8);
const pressure=VARIABLES.find(v=>v.key==='pressure_mid');assert.ok(axisDomain([1006,1012],pressure)[0]>1000);
assert.deepEqual(axisDomain([4,98],VARIABLES.find(v=>v.key==='humidity_avg')),[0,100]);
console.log('Comparison checks passed: pressure, period boundaries, leap alignment, gaps, rain totals and circular directions.');
